export function translate(lang: Lang, key: Key, vars?: Vars): string {
  const text = lang === 'vi' ? vi[key] : en[key]
  if (!vars) return text
  return text.replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? ''))
}

type I18n = {
  lang: Lang
  t: (key: Key, vars?: Vars) => string
  setLang: (lang: Lang) => void
}

const Ctx = createContext<I18n | null>(null)

export function LangProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => (localStorage.getItem('trim.lang') === 'vi' ? 'vi' : 'en'))
  const t = useCallback((key: Key, vars?: Vars) => translate(lang, key, vars), [lang])
  const setLang = useCallback((next: Lang) => {
    localStorage.setItem('trim.lang', next)
    setLangState(next)
    document.documentElement.lang = next
    void window.muot.setLang(next)
  }, [])
  useEffect(() => { document.documentElement.lang = lang }, [lang])
  return <Ctx.Provider value={{ lang, t, setLang }}>{children}</Ctx.Provider>
}

export function useI18n(): I18n {
  const ctx = useContext(Ctx)
  if (!ctx) throw new Error('useI18n outside provider')
  return ctx
}
