import fs from 'node:fs/promises'
import path from 'node:path'
import assert from 'node:assert/strict'
import { pathToFileURL } from 'node:url'
import { spawn } from 'node:child_process'
import { once } from 'node:events'
import { build } from 'esbuild'
await fs.mkdir('.qa', { recursive: true })
await build({ entryPoints: ['electron/cleanup.ts'], outfile: '.qa/cleanup-test.mjs', bundle: true, platform: 'node', format: 'esm' })
const { CleanupService } = await import(pathToFileURL(path.resolve('.qa/cleanup-test.mjs')))
const base = await fs.mkdtemp(path.resolve('.qa/cleanup-fixture-'))
const root = path.join(base, 'temp'), outside = path.join(base, 'documents')
await fs.mkdir(root); await fs.mkdir(outside)
const old = new Date(Date.now() - 10 * 86400000)
async function oldFile(file, text = 'old data') { await fs.writeFile(file, text); await fs.utimes(file, old, old) }
await oldFile(path.join(root, 'old.tmp'))
await fs.writeFile(path.join(root, 'recent.tmp'), 'new data')
await oldFile(path.join(outside, 'personal.txt'))
await fs.symlink(outside, path.join(root, 'junction'), 'junction')
await fs.mkdir(path.join(root, 'project')); await fs.writeFile(path.join(root, 'project', 'package.json'), '{}'); await oldFile(path.join(root, 'project', 'source.ts'))
await fs.link(path.join(outside, 'personal.txt'), path.join(root, 'hardlink.tmp'))
const service = new CleanupService([{ id: 'temp', root }])
let scan = await service.scan()
assert.equal(scan.groups[0].count, 1)
assert.equal(await fs.readFile(path.join(root, 'old.tmp'), 'utf8'), 'old data', 'scan must not delete')
await assert.rejects(service.clean('invalid', ['temp'], async () => true))
await assert.rejects(service.clean(scan.token, ['../documents'], async () => true))
let result = await service.clean(scan.token, ['temp'], async () => false)
assert(result.cancelled)
assert.equal(await fs.readFile(path.join(root, 'old.tmp'), 'utf8'), 'old data')
result = await service.clean(scan.token, ['temp'], async () => true)
assert.equal(result.deleted, 1)
await assert.rejects(fs.access(path.join(root, 'old.tmp')))
assert.equal(await fs.readFile(path.join(outside, 'personal.txt'), 'utf8'), 'old data')
assert.equal(await fs.readFile(path.join(root, 'recent.tmp'), 'utf8'), 'new data')
assert.equal(await fs.readFile(path.join(root, 'project', 'source.ts'), 'utf8'), 'old data')
await assert.rejects(service.clean(scan.token, ['temp'], async () => true), undefined, 'token must be single use')
await oldFile(path.join(root, 'changed.tmp'))
scan = await service.scan()
await fs.writeFile(path.join(root, 'changed.tmp'), 'keep this changed data')
result = await service.clean(scan.token, ['temp'], async () => true)
assert.equal(result.deleted, 0); assert.equal(result.skipped, 1)
await fs.mkdir(path.join(root, 'swap')); await oldFile(path.join(root, 'swap', 'personal.txt'))
scan = await service.scan()
await fs.rename(path.join(root, 'swap'), path.join(root, 'moved'))
await fs.symlink(outside, path.join(root, 'swap'), 'junction')
result = await service.clean(scan.token, ['temp'], async () => true)
assert.equal(result.deleted, 0)
assert.equal(await fs.readFile(path.join(outside, 'personal.txt'), 'utf8'), 'old data')
const expired = new CleanupService([{ id: 'temp', root }], { ttlMs: -1 })
const stale = await expired.scan()
await assert.rejects(expired.clean(stale.token, ['temp'], async () => true))
const capped = await new CleanupService([{ id: 'temp', root }], { maxEntries: 1 }).scan()
assert(capped.limited)
console.log('Cleanup fixtures passed: age, preview, cancellation, allowlist, single-use/expired tokens, symlink/junction/hardlink refusal, changed files, project exclusion, bounded scan. Fixtures retained under .qa.')

const lockedRoot = path.join(base, 'locked-root')
await fs.mkdir(lockedRoot)
const lockedFile = path.join(lockedRoot, 'locked.tmp')
await oldFile(lockedFile)
const holder = spawn('powershell.exe', ['-NoProfile', '-File', 'scripts/fixtures/lock-file.ps1', '-File', lockedFile], { windowsHide: true, stdio: ['pipe', 'pipe', 'pipe'] })
try {
  await Promise.race([once(holder.stdout, 'data'), once(holder, 'exit').then(() => { throw Error('Lock helper exited early') })])
  const locker = new CleanupService([{ id: 'temp', root: lockedRoot }])
  const lockedScan = await locker.scan()
  const lockedResult = await locker.clean(lockedScan.token, ['temp'], async () => true)
  assert.equal(lockedResult.deleted, 0)
  assert.equal(lockedResult.skipped, 1)
} finally { holder.stdin.end('done\n'); await once(holder, 'exit') }
assert.equal(await fs.readFile(lockedFile, 'utf8'), 'old data')
const newlyProject = new CleanupService([{ id: 'temp', root: lockedRoot }])
const projectScan = await newlyProject.scan()
await fs.writeFile(path.join(lockedRoot, 'package.json'), '{}')
assert.equal((await newlyProject.clean(projectScan.token, ['temp'], async () => true)).deleted, 0)
const renew = new CleanupService([{ id: 'temp', root }])
const first = await renew.scan()
await renew.scan()
await assert.rejects(renew.clean(first.token, ['temp'], async () => true))
console.log('Additional checks passed: Windows locked files, project marker added after scan, rescan invalidation.')
